-- Existing completed todos stay excluded even if they are reopened after this migration.
ALTER TABLE personal_todo ADD COLUMN reward_eligible BOOLEAN NOT NULL DEFAULT TRUE;
UPDATE personal_todo SET reward_eligible = FALSE WHERE completed_at IS NOT NULL;

CREATE TABLE character_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    activity_type VARCHAR(40) NOT NULL,
    activity_id BIGINT NOT NULL,
    exp_amount INTEGER NOT NULL CHECK (exp_amount > 0),
    earned_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_character_activity_once UNIQUE (user_id, activity_type, activity_id)
);
CREATE INDEX ix_character_activity_user_recent ON character_activity(user_id, earned_at DESC, id DESC);

CREATE TABLE character_reward (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    quest_id VARCHAR(40) NOT NULL,
    item_id VARCHAR(40) NOT NULL,
    claimed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_character_reward_quest UNIQUE (user_id, quest_id),
    CONSTRAINT uq_character_reward_item UNIQUE (user_id, item_id)
);
CREATE INDEX ix_character_reward_user ON character_reward(user_id);

