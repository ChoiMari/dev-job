ALTER TABLE personal_todo
    ADD COLUMN category VARCHAR(30) NOT NULL DEFAULT '기타',
    ADD COLUMN reminder_minutes INTEGER NOT NULL DEFAULT 1440;
ALTER TABLE personal_todo ADD CONSTRAINT ck_personal_todo_reminder_minutes
    CHECK (reminder_minutes IN (-1, 10, 60, 1440));

CREATE TABLE personal_todo_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(30) NOT NULL CHECK (length(btrim(name)) > 0),
    CONSTRAINT uq_personal_todo_category_user_name UNIQUE (user_id, name)
);
