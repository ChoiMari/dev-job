CREATE TABLE interested_company (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(200) NOT NULL CHECK (btrim(name) <> ''),
    website_url VARCHAR(2048),
    note VARCHAR(2000),
    status VARCHAR(20) NOT NULL CHECK (status IN ('INTERESTED', 'RESEARCHING', 'ARCHIVED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_interested_company_user_website UNIQUE (user_id, website_url)
);

CREATE INDEX ix_interested_company_user_created
    ON interested_company (user_id, created_at DESC, id DESC);
