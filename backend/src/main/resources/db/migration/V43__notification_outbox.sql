CREATE TABLE notification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(40) NOT NULL CHECK (type IN (
        'NEW_JOB', 'AI_JOB_RECOMMENDATION', 'SAVED_JOB_UPDATE',
        'DOCUMENT_ANALYSIS', 'MATCH_ANALYSIS', 'SEMANTIC_RECOMMENDATION',
        'CHARACTER_ACTIVITY', 'SERVICE_NOTICE')),
    source_id BIGINT NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    processed_at TIMESTAMPTZ,
    CONSTRAINT uq_notification_outbox_event UNIQUE (type, source_id, occurred_at)
);
CREATE INDEX ix_notification_outbox_pending ON notification_outbox(id) WHERE processed_at IS NULL;

-- Reconcile events created while V42's periodic scan was in use.
INSERT INTO notification_outbox(type, source_id, occurred_at)
SELECT 'NEW_JOB', j.id, j.created_at FROM job_posting j
JOIN ai_analysis a ON a.job_posting_id=j.id AND a.status='COMPLETED'
CROSS JOIN notification_delivery_start rollout
WHERE j.created_at >= rollout.started_at AND a.analyzed_at >= rollout.started_at
UNION ALL
SELECT 'AI_JOB_RECOMMENDATION', j.id, a.analyzed_at FROM job_posting j
JOIN ai_analysis a ON a.job_posting_id=j.id AND a.status='COMPLETED'
CROSS JOIN notification_delivery_start rollout WHERE a.analyzed_at >= rollout.started_at
UNION ALL
SELECT 'MATCH_ANALYSIS', a.job_posting_id, a.analyzed_at FROM ai_analysis a
CROSS JOIN notification_delivery_start rollout
WHERE a.status='COMPLETED' AND a.analyzed_at >= rollout.started_at
UNION ALL
SELECT 'SAVED_JOB_UPDATE', e.id, e.occurred_at FROM notification_job_update e
CROSS JOIN notification_delivery_start rollout WHERE e.occurred_at >= rollout.started_at
UNION ALL
SELECT 'DOCUMENT_ANALYSIS', a.id, a.analyzed_at FROM document_analysis a
CROSS JOIN notification_delivery_start rollout
WHERE a.status='COMPLETED' AND a.analyzed_at >= rollout.started_at
UNION ALL
SELECT 'SEMANTIC_RECOMMENDATION', r.id, r.analyzed_at FROM semantic_recommendation r
CROSS JOIN notification_delivery_start rollout
WHERE r.status='COMPLETED' AND r.analyzed_at >= rollout.started_at
UNION ALL
SELECT 'CHARACTER_ACTIVITY', a.id * 2, a.earned_at FROM character_activity a
CROSS JOIN notification_delivery_start rollout WHERE a.earned_at >= rollout.started_at
UNION ALL
SELECT 'CHARACTER_ACTIVITY', r.id * 2 + 1, r.claimed_at FROM character_reward r
CROSS JOIN notification_delivery_start rollout WHERE r.claimed_at >= rollout.started_at
UNION ALL
SELECT 'SERVICE_NOTICE', n.id, n.published_at FROM service_notice n
CROSS JOIN notification_delivery_start rollout WHERE n.published_at >= rollout.started_at
ON CONFLICT (type, source_id, occurred_at) DO NOTHING;
