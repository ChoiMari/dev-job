CREATE TABLE semantic_recommendation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    resume_version_id BIGINT REFERENCES resume_version(id) ON DELETE CASCADE,
    cover_letter_version_id BIGINT REFERENCES cover_letter_version(id) ON DELETE CASCADE,
    input_hash CHAR(64) NOT NULL,
    policy_version VARCHAR(20) NOT NULL,
    model_name VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    candidates JSONB NOT NULL,
    result_ciphertext BYTEA,
    result_nonce BYTEA CHECK (result_nonce IS NULL OR octet_length(result_nonce) = 12),
    failure_reason VARCHAR(200),
    consented_at TIMESTAMPTZ NOT NULL,
    analyzed_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_semantic_document CHECK (resume_version_id IS NOT NULL OR cover_letter_version_id IS NOT NULL),
    CONSTRAINT ck_semantic_result_pair CHECK ((result_ciphertext IS NULL) = (result_nonce IS NULL)),
    CONSTRAINT uq_semantic_input UNIQUE (user_id, input_hash)
);
CREATE INDEX ix_semantic_user_time ON semantic_recommendation(user_id, updated_at DESC, id DESC);
