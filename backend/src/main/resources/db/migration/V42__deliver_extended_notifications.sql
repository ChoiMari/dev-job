CREATE TABLE notification_job_update (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_posting_id BIGINT NOT NULL REFERENCES job_posting(id),
    occurred_at TIMESTAMPTZ NOT NULL,
    subject VARCHAR(200) NOT NULL
);
CREATE INDEX ix_notification_job_update_time ON notification_job_update(occurred_at, id);

CREATE TABLE service_notice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    published_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    title VARCHAR(200) NOT NULL CHECK (length(btrim(title)) > 0),
    published_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
