CREATE TABLE learning_goal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    skill_id BIGINT REFERENCES skill(id),
    title VARCHAR(200) NOT NULL CHECK (length(btrim(title)) > 0),
    description VARCHAR(2000),
    progress_percent INTEGER NOT NULL DEFAULT 0 CHECK (progress_percent BETWEEN 0 AND 100),
    completed_at TIMESTAMP WITH TIME ZONE,
    deleted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_learning_goal_completion_progress CHECK (completed_at IS NULL OR progress_percent = 100)
);
CREATE UNIQUE INDEX uq_learning_goal_active_identity
    ON learning_goal (user_id, coalesce(skill_id, -1), title) WHERE deleted_at IS NULL;
CREATE INDEX ix_learning_goal_user_updated
    ON learning_goal (user_id, updated_at DESC, id DESC) WHERE deleted_at IS NULL;
