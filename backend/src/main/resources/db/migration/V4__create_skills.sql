CREATE TABLE skill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),
    normalized_name VARCHAR(100) NOT NULL UNIQUE CHECK (length(btrim(normalized_name)) > 0)
);
CREATE TABLE skill_alias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id BIGINT NOT NULL REFERENCES skill(id),
    alias_name VARCHAR(100) NOT NULL CHECK (length(btrim(alias_name)) > 0),
    normalized_name VARCHAR(100) NOT NULL UNIQUE CHECK (length(btrim(normalized_name)) > 0)
);
CREATE INDEX ix_skill_alias_skill ON skill_alias(skill_id);
CREATE TABLE user_skill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    skill_id BIGINT NOT NULL REFERENCES skill(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_user_skill UNIQUE (user_id, skill_id)
);
CREATE INDEX ix_user_skill_skill ON user_skill(skill_id);

