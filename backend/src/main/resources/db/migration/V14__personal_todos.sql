CREATE TABLE personal_todo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(200) NOT NULL CHECK (length(btrim(title)) > 0),
    description VARCHAR(2000),
    due_at TIMESTAMP WITH TIME ZONE,
    due_time_zone VARCHAR(100),
    completed_at TIMESTAMP WITH TIME ZONE,
    deleted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_personal_todo_due_pair CHECK ((due_at IS NULL) = (due_time_zone IS NULL))
);
CREATE INDEX ix_personal_todo_user_due ON personal_todo(user_id, due_at ASC NULLS LAST, id DESC) WHERE deleted_at IS NULL;
