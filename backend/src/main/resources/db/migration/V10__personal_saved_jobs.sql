CREATE TABLE personal_saved_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    url VARCHAR(2048) NOT NULL,
    company_name VARCHAR(200) NOT NULL,
    title VARCHAR(300) NOT NULL,
    role VARCHAR(120),
    career_level VARCHAR(120),
    location VARCHAR(200),
    employment_type VARCHAR(120),
    deadline_date DATE,
    note VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE
);
CREATE UNIQUE INDEX uk_personal_saved_job_active_url ON personal_saved_job(user_id, url) WHERE deleted_at IS NULL;
CREATE INDEX ix_personal_saved_job_user_created ON personal_saved_job(user_id, created_at DESC, id DESC) WHERE deleted_at IS NULL;
ALTER TABLE application ALTER COLUMN job_posting_id DROP NOT NULL;
ALTER TABLE application ADD COLUMN personal_saved_job_id BIGINT REFERENCES personal_saved_job(id);
ALTER TABLE application ADD CONSTRAINT ck_application_one_job CHECK
    ((job_posting_id IS NOT NULL AND personal_saved_job_id IS NULL) OR
     (job_posting_id IS NULL AND personal_saved_job_id IS NOT NULL));
CREATE UNIQUE INDEX uk_application_user_personal_job ON application(user_id, personal_saved_job_id)
    WHERE personal_saved_job_id IS NOT NULL;
