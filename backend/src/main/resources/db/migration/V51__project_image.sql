CREATE TABLE project_image (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES project(id) ON DELETE CASCADE,
    object_key VARCHAR(300) NOT NULL UNIQUE,
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('THUMBNAIL', 'ADDITIONAL')),
    status VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'READY')),
    original_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(32) NOT NULL,
    byte_size BIGINT NOT NULL CHECK (byte_size BETWEEN 1 AND 5242880),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_project_image_project ON project_image(project_id);
