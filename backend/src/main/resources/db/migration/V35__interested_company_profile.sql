ALTER TABLE interested_company
    ADD COLUMN industry VARCHAR(80),
    ADD COLUMN company_size VARCHAR(20),
    ADD COLUMN region VARCHAR(80),
    ADD COLUMN interest_level VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',
    ADD COLUMN favorite BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE interested_company ADD CONSTRAINT ck_interested_company_size
    CHECK (company_size IS NULL OR company_size IN ('STARTUP', 'SMALL', 'MEDIUM', 'LARGE'));
ALTER TABLE interested_company ADD CONSTRAINT ck_interested_company_interest_level
    CHECK (interest_level IN ('HIGH', 'MEDIUM', 'LOW'));

CREATE TABLE interested_company_tag (
    company_id BIGINT NOT NULL REFERENCES interested_company(id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    tag VARCHAR(30) NOT NULL,
    PRIMARY KEY (company_id, position),
    CONSTRAINT uk_interested_company_tag UNIQUE (company_id, tag)
);

CREATE TABLE personal_company_tag (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(30) NOT NULL CHECK (btrim(name) <> ''),
    CONSTRAINT uk_personal_company_tag_user_name UNIQUE (user_id, name)
);

CREATE INDEX ix_personal_company_tag_user ON personal_company_tag (user_id, id);
CREATE INDEX ix_interested_company_filter ON interested_company (user_id, interest_level, created_at DESC);
