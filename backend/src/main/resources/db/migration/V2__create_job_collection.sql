CREATE TABLE company (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (btrim(name) <> '')
);

CREATE TABLE job_source (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE CHECK (btrim(code) <> ''),
    name TEXT
);

CREATE TABLE job_posting (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_source_id BIGINT NOT NULL REFERENCES job_source(id),
    external_id TEXT NOT NULL CHECK (btrim(external_id) <> ''),
    company_id BIGINT NOT NULL REFERENCES company(id),
    title TEXT NOT NULL CHECK (btrim(title) <> ''),
    description TEXT,
    employment_type TEXT,
    career_requirement TEXT,
    location TEXT,
    posted_date DATE,
    deadline_date DATE,
    source_url TEXT NOT NULL CHECK (btrim(source_url) <> ''),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_job_posting_source_external UNIQUE (job_source_id, external_id),
    CONSTRAINT ck_job_posting_dates CHECK (
        posted_date IS NULL OR deadline_date IS NULL OR deadline_date >= posted_date
    )
);
