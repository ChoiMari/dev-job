CREATE TABLE cover_letter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(200) NOT NULL CHECK (length(btrim(title)) > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_cover_letter_owner_active ON cover_letter(user_id, updated_at DESC, id DESC) WHERE deleted_at IS NULL;
CREATE INDEX ix_cover_letter_expiry ON cover_letter(deleted_at) WHERE deleted_at IS NOT NULL;

CREATE TABLE cover_letter_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cover_letter_id BIGINT NOT NULL REFERENCES cover_letter(id),
    version_number INTEGER NOT NULL CHECK (version_number > 0),
    content_ciphertext BYTEA NOT NULL,
    content_nonce BYTEA NOT NULL CHECK (octet_length(content_nonce) = 12),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_cover_letter_version_number UNIQUE (cover_letter_id, version_number)
);
CREATE INDEX ix_cover_letter_version_order ON cover_letter_version(cover_letter_id, version_number DESC);

CREATE TABLE document_analysis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resume_version_id BIGINT UNIQUE REFERENCES resume_version(id) ON DELETE CASCADE,
    cover_letter_version_id BIGINT UNIQUE REFERENCES cover_letter_version(id) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    result_ciphertext BYTEA,
    result_nonce BYTEA CHECK (result_nonce IS NULL OR octet_length(result_nonce) = 12),
    failure_reason VARCHAR(200),
    consented_at TIMESTAMP WITH TIME ZONE NOT NULL,
    analyzed_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_document_analysis_one_source CHECK ((resume_version_id IS NULL) <> (cover_letter_version_id IS NULL)),
    CONSTRAINT ck_document_analysis_result_pair CHECK ((result_ciphertext IS NULL) = (result_nonce IS NULL))
);
