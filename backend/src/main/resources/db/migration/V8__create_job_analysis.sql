CREATE TABLE ai_analysis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_posting_id BIGINT NOT NULL UNIQUE REFERENCES job_posting(id),
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    result_json JSONB,
    failure_reason VARCHAR(200),
    analyzed_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE job_skill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_posting_id BIGINT NOT NULL REFERENCES job_posting(id),
    skill_id BIGINT NOT NULL REFERENCES skill(id),
    requirement_type VARCHAR(20) NOT NULL CHECK (requirement_type IN ('REQUIRED', 'PREFERRED')),
    CONSTRAINT uq_job_skill UNIQUE (job_posting_id, skill_id)
);
CREATE INDEX ix_job_skill_skill ON job_skill(skill_id);
