CREATE TABLE project (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),
    description VARCHAR(2000),
    start_date DATE NOT NULL,
    end_date DATE CHECK (end_date IS NULL OR end_date >= start_date),
    role VARCHAR(100),
    key_features VARCHAR(2000),
    outcome VARCHAR(2000),
    project_url VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_project_user_created ON project(user_id, created_at DESC, id DESC);

CREATE TABLE project_skill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES project(id),
    skill_id BIGINT NOT NULL REFERENCES skill(id),
    CONSTRAINT uq_project_skill UNIQUE (project_id, skill_id)
);
CREATE INDEX idx_project_skill_skill ON project_skill(skill_id);
