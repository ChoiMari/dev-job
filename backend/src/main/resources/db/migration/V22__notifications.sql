CREATE TABLE notification_preference (
    user_id BIGINT NOT NULL REFERENCES users(id),
    type VARCHAR(30) NOT NULL CHECK (type IN ('INTERVIEW_REMINDER', 'TODO_REMINDER')),
    enabled BOOLEAN NOT NULL,
    PRIMARY KEY (user_id, type)
);

CREATE TABLE notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    type VARCHAR(30) NOT NULL CHECK (type IN ('INTERVIEW_REMINDER', 'TODO_REMINDER')),
    source_id BIGINT NOT NULL,
    scheduled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    subject VARCHAR(200) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_notification_event UNIQUE (user_id, type, source_id, scheduled_at)
);
CREATE INDEX ix_notification_user_created ON notification(user_id, created_at DESC, id DESC);
CREATE INDEX ix_interview_notification_due ON interview_schedule(starts_at, id) WHERE cancelled_at IS NULL;
CREATE INDEX ix_todo_notification_due ON personal_todo(due_at, id) WHERE deleted_at IS NULL AND completed_at IS NULL AND due_at IS NOT NULL;
