CREATE TABLE resume (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(200) NOT NULL CHECK (length(btrim(title)) > 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_resume_owner_active ON resume(user_id, updated_at DESC, id DESC) WHERE deleted_at IS NULL;
CREATE INDEX ix_resume_expiry ON resume(deleted_at) WHERE deleted_at IS NOT NULL;

CREATE TABLE resume_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resume_id BIGINT NOT NULL REFERENCES resume(id),
    version_number INTEGER NOT NULL CHECK (version_number > 0),
    content_ciphertext BYTEA NOT NULL,
    content_nonce BYTEA NOT NULL CHECK (octet_length(content_nonce) = 12),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_resume_version_number UNIQUE (resume_id, version_number)
);
CREATE INDEX ix_resume_version_order ON resume_version(resume_id, version_number DESC);
