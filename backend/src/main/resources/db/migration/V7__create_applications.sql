CREATE TABLE application (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    job_posting_id BIGINT NOT NULL REFERENCES job_posting(id),
    current_status VARCHAR(30) NOT NULL CHECK (current_status IN
        ('INTERESTED','PLANNED','APPLIED','DOCUMENT_PASSED','INTERVIEW','FINAL_PASSED','REJECTED','WITHDRAWN')),
    applied_date DATE,
    next_schedule_at TIMESTAMP WITH TIME ZONE,
    note VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_application_user_job UNIQUE (user_id, job_posting_id),
    CONSTRAINT ck_application_applied_date CHECK
        (current_status NOT IN ('APPLIED','DOCUMENT_PASSED','INTERVIEW','FINAL_PASSED','REJECTED') OR applied_date IS NOT NULL)
);
CREATE INDEX ix_application_user_status ON application(user_id, current_status, created_at DESC, id DESC);
CREATE TABLE application_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES application(id),
    from_status VARCHAR(30) CHECK (from_status IN
        ('INTERESTED','PLANNED','APPLIED','DOCUMENT_PASSED','INTERVIEW','FINAL_PASSED','REJECTED','WITHDRAWN')),
    to_status VARCHAR(30) NOT NULL CHECK (to_status IN
        ('INTERESTED','PLANNED','APPLIED','DOCUMENT_PASSED','INTERVIEW','FINAL_PASSED','REJECTED','WITHDRAWN')),
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK (from_status IS NULL OR from_status <> to_status)
);
CREATE INDEX ix_application_history_order ON application_status_history(application_id, changed_at, id);
