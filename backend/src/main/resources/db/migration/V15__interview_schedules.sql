CREATE TABLE interview_schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    application_id BIGINT REFERENCES application(id),
    title VARCHAR(200) NOT NULL CHECK (length(btrim(title)) > 0),
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
    time_zone VARCHAR(100) NOT NULL,
    cancelled_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_interview_schedule_user_start ON interview_schedule(user_id, starts_at, id DESC);
CREATE INDEX ix_interview_schedule_application ON interview_schedule(application_id);
