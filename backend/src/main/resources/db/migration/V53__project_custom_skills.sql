CREATE TABLE project_custom_skill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES project(id),
    name VARCHAR(100) NOT NULL,
    normalized_name VARCHAR(100) NOT NULL,
    usage_note VARCHAR(1000),
    CONSTRAINT uq_project_custom_skill_name UNIQUE (project_id, normalized_name),
    CONSTRAINT ck_project_custom_skill_name CHECK (length(btrim(name)) > 0)
);

CREATE INDEX idx_project_custom_skill_project ON project_custom_skill(project_id);
