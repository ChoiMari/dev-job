CREATE TABLE user_custom_skill (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),
 normalized_name VARCHAR(100) NOT NULL CHECK (length(btrim(normalized_name)) > 0),
 proficiency_level INTEGER CHECK (proficiency_level BETWEEN 1 AND 5),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_user_custom_skill UNIQUE (user_id, normalized_name)
);
CREATE INDEX ix_user_custom_skill_user ON user_custom_skill(user_id);

CREATE TABLE user_ai_analysis_request (
 user_id BIGINT NOT NULL REFERENCES users(id),
 job_posting_id BIGINT NOT NULL REFERENCES job_posting(id) ON DELETE CASCADE,
 PRIMARY KEY (user_id, job_posting_id)
);
CREATE INDEX ix_user_ai_analysis_request_job ON user_ai_analysis_request(job_posting_id);

CREATE TABLE user_ai_skill_candidate (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),
 normalized_name VARCHAR(100) NOT NULL CHECK (length(btrim(normalized_name)) > 0),
 source_job_posting_id BIGINT REFERENCES job_posting(id) ON DELETE SET NULL,
 source_personal_saved_job_id BIGINT REFERENCES personal_saved_job(id) ON DELETE SET NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_user_ai_skill_candidate UNIQUE (user_id, normalized_name)
);
CREATE INDEX ix_user_ai_skill_candidate_user ON user_ai_skill_candidate(user_id);
